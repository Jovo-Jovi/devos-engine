// only on these labels, so they are made before anyone can file an issue.
export const FORM_LABELS = [
  ["devos:request", "1d76db", "A change request for DEV_OS to plan (the Dev OS change request form)"],
  ["devos:method", "5319e7", "A DEV_OS method fix (the Dev OS method fix form)"],
];

function profileOwner() {
  try {
    const file = path.join(devosHome(), ".devos", "profile.json");
    if (!existsSync(file)) return "";
    const data = JSON.parse(readFileSync(file, "utf8"));
    if (data && typeof data.github_owner === "string" && data.github_owner.length > 0) return data.github_owner;
  } catch {
    /* an unreadable profile falls through to gh */
  }
  return "";
}

function stopped(folder, step, result) {
  const stderr = result?.stderr ?? "";
  if (stderr) process.stderr.write(stderr.endsWith("\n") ? stderr : `${stderr}\n`);
  console.log(`devos: setup stopped at ${step}; fix it, then run: devos continue ${folder}`);
  return 1;
}

function git(folder, args) {
  return run("git", args, { cwd: folder, timeout: RUN.timeout });
}

function secretNamesOnRepo(folder, slug) {
  const listed = run("gh", ["secret", "list", "--repo", slug, "--json", "name"], { cwd: folder, timeout: RUN.timeout });
  if (!listed || listed.status !== 0) return null;
  try {
    return new Set(JSON.parse(listed.stdout).map((row) => row.name));
  } catch {
    return null;
  }
}

function adoptEmptyRepo(folder, slug, created) {
  const viewed = run("gh", ["repo", "view", slug, "--json", "name,isEmpty,url"], { cwd: folder, timeout: RUN.timeout });
  if (!viewed || viewed.status !== 0) return stopped(folder, "repository", created);
  let info;
  try {
    info = JSON.parse(viewed.stdout);
  } catch {
    return stopped(folder, "repository", created);
  }
  if (info.isEmpty !== true) {
    console.log(`devos: ${slug} already exists and has commits; delete it or change "name" in devos/answers.json, then run devos continue ${folder}`);
    return 1;
  }
  const url = `${String(info.url ?? "").replace(/\.git$/, "")}.git`;
  const current = git(folder, ["remote", "get-url", "origin"]);
  const aimed = current && current.status === 0
    ? git(folder, ["remote", "set-url", "origin", url])
    : git(folder, ["remote", "add", "origin", url]);
  if (!aimed || aimed.status !== 0) return stopped(folder, "repository", aimed);
  console.log(`devos: adopted the existing empty repository ${slug}`);
  return true;
}

function delay(ms) {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

function secretNames(setup) {
  const names = [];
  for (const item of setup.items ?? []) {
    if (item.kind !== "secret") continue;
    for (const name of item.names) {
      if (!names.includes(name)) names.push(name);
    }
  }
  return names;
}

function projectAgents(folder) {
  try {
    const config = JSON.parse(readFileSync(path.join(folder, "devos.config.json"), "utf8"));
    return config.agents ?? {};
  } catch {
    return {};
  }
}

function interactive(read) {
  if (read && typeof read.interactive === "boolean") return read.interactive;
  if (read && typeof read.isTTY === "boolean") return read.isTTY;
  return Boolean(process.stdin.isTTY);
}

export function repoSlug(owner, answers) {
  return `${owner}/${keyFromName(answers.name).toLowerCase()}`;
}

function uiLine(tag, payload) {
  if (process.env.DEVOS_UI !== "1") return;
  process.stdout.write("\n");
  console.log(`${tag} ${JSON.stringify(payload)}`);
}

function uiStep(payload) {
  uiLine("::devos-step", payload);
}

function uiAsk(payload) {
  uiLine("::devos-ask", payload);
}

export async function finishSetup(folder, answers, read) {
  const keys = new Map();
  try {
    return await completeSetup(folder, answers, read, keys);
  } finally {
    keys.clear();
  }
}

async function completeSetup(folder, answers, read, keys) {
  uiStep({ step: "owner" });
  let owner = profileOwner();
  if (!owner) {
    const login = run("gh", ["api", "user", "--jq", ".login"], { cwd: folder, timeout: RUN.timeout });
    if (!login || login.status !== 0) return stopped(folder, "owner", login);
    owner = String(login.stdout ?? "").trim();
    if (!owner) return stopped(folder, "owner", login);
  }
  const slug = repoSlug(owner, answers);

  uiStep({ step: "setup" });
  let setup;
  try {
    setup = JSON.parse(readFileSync(path.join(folder, "devos", "setup.json"), "utf8"));
  } catch (error) {
    return stopped(folder, "setup", { stderr: `${error.message}\n` });
  }
  const items = setupItems(setup, answers, folder);
  let needed = neededKeys(setup, answers, projectAgents(folder));
  const originEarly = git(folder, ["remote", "get-url", "origin"]);
  if (originEarly && originEarly.status === 0) {
    const viewed = run("gh", ["repo", "view", slug, "--json", "name"], { cwd: folder, timeout: RUN.timeout });
    if (viewed && viewed.status === 0) {
      const listed = secretNamesOnRepo(folder, slug);
      if (listed) needed = needed.filter((key) => !listed.has(key.name));
    }
  }
  uiStep({ step: "keys" });
  if (interactive(read)) {
    console.log("Keys this project needs (typed once, hidden; they go only to GitHub):");
    for (const key of needed) console.log(`- ${key.name} — ${key.where}`);
    for (let index = 0; index < needed.length; index += 1) {
      const key = needed[index];
      uiAsk({
        kind: "key",
        name: key.name,
        where: key.where,
        optional: Boolean(key.optional),
        file: Boolean(key.file),
        index,
        total: needed.length,
      });
      const value = key.file
        ? await readFileKey(key.name, read, process.stdout)
        : await secret(read, process.stdout, `${key.name} (Enter to skip)`);
      if (value === null || value === undefined) return 1;
      if (value !== "") keys.set(key.name, value);
    }
  } else {
    console.log("devos: set these yourself (gh asks for each value):");
    for (const key of needed) {
      if (key.optional) continue;
      console.log(`gh secret set ${key.name} --repo ${slug}`);
    }
  }
  const visibility = answers.visibility === "public" ? "public" : "private";
  // E10a: DEVOS_REPORTING is set only when the developer answered yes to the Control Tower link.
  const variableNames = [...items.filter((item) => item.kind === "variable").flatMap((item) => item.names), ...(answers.registry_link === true ? ["DEVOS_REPORTING"] : [])];
  const uploadNames = needed.filter((key) => keys.has(key.name)).map((key) => key.name);
  const laterNames = needed.filter((key) => !keys.has(key.name)).map((key) => key.name);
  console.log(`Ready to create ${slug} (${visibility}) on GitHub and push the project.`);
  console.log(`Variables: ${variableNames.length > 0 ? variableNames.join(", ") : "none"}.`);
  console.log(`Keys to upload: ${uploadNames.length > 0 ? uploadNames.join(", ") : "none"}; to set later: ${laterNames.length > 0 ? laterNames.join(", ") : "none"}.`);
  uiAsk({ kind: "create", slug, visibility, variables: variableNames, upload: uploadNames, later: laterNames });
  const create = await confirm(read, process.stdout, "Create it now?", true);
  if (create === null || create === undefined) return 1;
  if (!create) {
    keys.clear();
    console.log(`devos: stopped before GitHub — nothing was created; run devos continue ${folder} when ready`);
    return 0;
  }
  const readme = path.join(folder, "README.md");
  if (!existsSync(readme)) writeFileSync(readme, projectReadme(answers, slug));
  writeFileSync(path.join(folder, "SETUP.md"), setupMarkdown(items, { name: answers.name, slug, appKeys: catalogueAppKeys(answers.modules ?? {}) }));

  uiStep({ step: "commit" });
  if (!existsSync(path.join(folder, ".git"))) {
    const init = git(folder, ["init", "-b", "main"]);
    if (!init || init.status !== 0) return stopped(folder, "commit", init);
  }
  const added = git(folder, ["add", "-A"]);
  if (!added || added.status !== 0) return stopped(folder, "commit", added);
  const status = git(folder, ["status", "--porcelain"]);
  if (!status || status.status !== 0) return stopped(folder, "commit", status);
  if (String(status.stdout ?? "").trim() !== "") {
    const commit = git(folder, ["commit", "-m", `DEV_OS bootstrap: ${answers.name}`]);
    if (!commit || commit.status !== 0) return stopped(folder, "commit", commit);
  }

  uiStep({ step: "repository" });
  const remote = git(folder, ["remote", "get-url", "origin"]);
  if (!remote || remote.status !== 0) {
    const created = run("gh", ["repo", "create", slug, `--${visibility}`, "--source", ".", "--remote", "origin"], {
      cwd: folder,
      timeout: RUN.timeout,
    });
    if (!created || created.status !== 0) {
      const adopted = adoptEmptyRepo(folder, slug, created);
      if (adopted !== true) return adopted;
    }
  }
  const pushed = git(folder, ["push", "-u", "origin", "main"]);
  if (!pushed || pushed.status !== 0) {
    const stderr = pushed?.stderr ?? "";
    if (/\[rejected\]|non-fast-forward|fetch first/i.test(stderr)) {
      if (stderr) process.stderr.write(stderr.endsWith("\n") ? stderr : `${stderr}\n`);
      console.log(`devos: GitHub refused the push to ${slug} (it has commits this folder does not); nothing was overwritten`);
      return 1;
    }
    return stopped(folder, "repository", pushed);
  }

  uiStep({ step: "permissions" });
  const permissions = run("gh", [
    "api",
    "-X",
    "PUT",
    `repos/${slug}/actions/permissions/workflow`,
    "-f",
    "default_workflow_permissions=write",
    "-F",
    "can_approve_pull_request_reviews=true",
  ], { cwd: folder, timeout: RUN.timeout });
  if (!permissions || permissions.status !== 0) return stopped(folder, "permissions", permissions);
  for (const [name, color, description] of FORM_LABELS) {
    const label = run("gh", ["label", "create", name, "--color", color, "--description", description, "--force", "--repo", slug], {
      cwd: folder,
      timeout: RUN.timeout,
    });
    if (!label || label.status !== 0) return stopped(folder, "permissions", label);
  }
  // DEV_OS uses neither GitHub's Wiki nor its Projects tab: both are turned off.
  const features = run("gh", ["repo", "edit", slug, "--enable-wiki=false", "--enable-projects=false"], { cwd: folder, timeout: RUN.timeout });
  if (!features || features.status !== 0) return stopped(folder, "permissions", features);

  uiStep({ step: "variables" });
  for (const item of items) {
    if (item.kind !== "variable") continue;
    for (const name of item.names) {
      const set = run("gh", ["variable", "set", name, "--body", String(item.value), "--repo", slug], {
        cwd: folder,
        timeout: RUN.timeout,
      });
      if (!set || set.status !== 0) return stopped(folder, "variables", set);
    }
  }
  if (answers.registry_link === true) {
    const set = run("gh", ["variable", "set", "DEVOS_REPORTING", "--body", "on", "--repo", slug], { cwd: folder, timeout: RUN.timeout });
    if (!set || set.status !== 0) return stopped(folder, "variables", set);
  }

  uiStep({ step: "secrets" });
  if (interactive(read)) {
    for (const key of needed) {
      if (keys.has(key.name)) continue;
      console.log(`gh secret set ${key.name} --repo ${slug}`);
    }
  }
  for (const key of needed) {
    if (!keys.has(key.name)) continue;
    const value = keys.get(key.name);
    keys.delete(key.name);
    const set = run("gh", ["secret", "set", key.name, "--repo", slug], {
      cwd: folder,
      input: value,
      timeout: 120000,
    });
    if (!set || set.status !== 0) return stopped(folder, "secrets", set);
    console.log(`uploaded ${key.name}`);
  }

  uiStep({ step: "check" });
  const secretList = run("gh", ["secret", "list", "--repo", slug, "--json", "name"], { cwd: folder, timeout: RUN.timeout });
  if (!secretList || secretList.status !== 0) return stopped(folder, "check", secretList);
  const variableList = run("gh", ["variable", "list", "--repo", slug, "--json", "name,value"], {
    cwd: folder,
    timeout: RUN.timeout,
  });
  if (!variableList || variableList.status !== 0) return stopped(folder, "check", variableList);
  let listed;
  let variables;
  try {
    listed = new Set(JSON.parse(secretList.stdout).map((row) => row.name));
    variables = {};
    for (const row of JSON.parse(variableList.stdout)) variables[row.name] = row.value;
  } catch {
    return stopped(folder, "check", secretList);
  }
  const secretsJson = {};
  for (const name of secretNames(setup)) secretsJson[name] = listed.has(name) ? "1" : "";
  const env = {
    ...process.env,
    SECRETS_JSON: JSON.stringify(secretsJson),
    VARS_JSON: JSON.stringify(variables),
  };
  delete env.VERCEL_TOKEN;
  delete env.VERCEL_ORG_ID;
  delete env.VERCEL_PROJECT_ID;
  const check = spawnSync(process.execPath, ["scripts/devos/setup-check.mjs", "--for", "cycle"], {
    cwd: folder,
    encoding: "utf8",
    windowsHide: true,
    env,
  });
  if (check.stdout) process.stdout.write(check.stdout);
  if (check.status !== 0) {
    console.log(`devos: the cycle still needs settings (see SETUP.md); add them, then run: devos continue ${folder}`);
    return 1;
  }

  uiStep({ step: "cycle" });
  const wait = Number(process.env.DEVOS_RETRY_MS ?? 10000);
  let dispatched = null;
  for (let attempt = 0; attempt < 3; attempt += 1) {
    if (attempt > 0) await delay(wait);
    dispatched = run("gh", ["workflow", "run", "devos-cycle.yml", "--repo", slug], { cwd: folder, timeout: RUN.timeout });
    if (dispatched && dispatched.status === 0) break;
  }
  if (!dispatched || dispatched.status !== 0) return stopped(folder, "cycle", dispatched);
  console.log(`devos init: ${slug} is set up; devos-cycle dispatched`);
  return 0;
}
