import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { keyFromName } from "./install.mjs";
import { devosHome } from "./profile.mjs";
import { run } from "./which.mjs";

const RUN = { timeout: 120000 };

function holds(cond, answers) {
  if (cond === "always") return true;
  if (cond === "method") return false;
  if (cond === "var:DEVOS_VERCEL") return answers.deploy === "vercel";
  if (cond.startsWith("module:")) return false;
  return false;
}

export function setupItems(setup, answers) {
  return (setup.items ?? []).filter((item) => {
    const when = item.when ?? ["always"];
    if (!when.every((cond) => holds(cond, answers))) return false;
    if (item.id === "vercel-var" && answers.deploy !== "vercel") return false;
    return true;
  });
}

export function setupMarkdown(items, { name, slug }) {
  const lines = [
    `# SETUP — ${name}`,
    "",
    "Generated by devos init from devos/setup.json. Names only: DEV_OS never reads or stores a value.",
  ];
  items.forEach((item, index) => {
    lines.push("", `## ${index + 1}. ${item.title}`, "", `Names: ${item.names.map((entry) => `\`${entry}\``).join(", ")}`, "");
    item.steps.forEach((step, stepIndex) => {
      lines.push(`${stepIndex + 1}. ${step}`);
    });
    if (item.kind === "secret") {
      lines.push("", "```");
      for (const entry of item.names) lines.push(`gh secret set ${entry} --repo ${slug}`);
      lines.push("```");
    } else if (item.kind === "variable") {
      lines.push("", "```");
      for (const entry of item.names) lines.push(`gh variable set ${entry} --body ${item.value} --repo ${slug}`);
      lines.push("```");
    }
  });
  return `${lines.join("\n")}\n`;
}

function profileOwner() {
  try {
    const file = path.join(devosHome(), ".devos", "profile.json");
    if (!existsSync(file)) return "";
    const data = JSON.parse(readFileSync(file, "utf8"));
    if (data && typeof data.github_owner === "string" && data.github_owner.length > 0) return data.github_owner;
  } catch {
    /* an unreadable profile falls through to gh */
  }
  return "";
}

function stopped(folder, step, result) {
  const stderr = result?.stderr ?? "";
  if (stderr) process.stderr.write(stderr.endsWith("\n") ? stderr : `${stderr}\n`);
  console.log(`devos: setup stopped at ${step}; fix it, then run: devos init --continue ${folder}`);
  return 1;
}

function git(folder, args) {
  return run("git", args, { cwd: folder, timeout: RUN.timeout });
}

function delay(ms) {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

function secretNames(setup) {
  const names = [];
  for (const item of setup.items ?? []) {
    if (item.kind !== "secret") continue;
    for (const name of item.names) {
      if (!names.includes(name)) names.push(name);
    }
  }
  return names;
}

export async function finishSetup(folder, answers, read) {
  let owner = profileOwner();
  if (!owner) {
    const login = run("gh", ["api", "user", "--jq", ".login"], { cwd: folder, timeout: RUN.timeout });
    if (!login || login.status !== 0) return stopped(folder, "owner", login);
    owner = String(login.stdout ?? "").trim();
    if (!owner) return stopped(folder, "owner", login);
  }
  const slug = `${owner}/${keyFromName(answers.name).toLowerCase()}`;

  let setup;
  try {
    setup = JSON.parse(readFileSync(path.join(folder, "devos", "setup.json"), "utf8"));
  } catch (error) {
    return stopped(folder, "setup", { stderr: `${error.message}\n` });
  }
  const items = setupItems(setup, answers);
  writeFileSync(path.join(folder, "SETUP.md"), setupMarkdown(items, { name: answers.name, slug }));

  if (!existsSync(path.join(folder, ".git"))) {
    const init = git(folder, ["init", "-b", "main"]);
    if (!init || init.status !== 0) return stopped(folder, "commit", init);
  }
  const added = git(folder, ["add", "-A"]);
  if (!added || added.status !== 0) return stopped(folder, "commit", added);
  const status = git(folder, ["status", "--porcelain"]);
  if (!status || status.status !== 0) return stopped(folder, "commit", status);
  if (String(status.stdout ?? "").trim() !== "") {
    const commit = git(folder, ["commit", "-m", `DEV_OS bootstrap: ${answers.name}`]);
    if (!commit || commit.status !== 0) return stopped(folder, "commit", commit);
  }

  const remote = git(folder, ["remote", "get-url", "origin"]);
  if (!remote || remote.status !== 0) {
    const visibility = answers.visibility === "public" ? "public" : "private";
    const created = run("gh", ["repo", "create", slug, `--${visibility}`, "--source", ".", "--remote", "origin"], {
      cwd: folder,
      timeout: RUN.timeout,
    });
    if (!created || created.status !== 0) return stopped(folder, "repository", created);
  }
  const pushed = git(folder, ["push", "-u", "origin", "main"]);
  if (!pushed || pushed.status !== 0) return stopped(folder, "repository", pushed);

  const permissions = run("gh", [
    "api",
    "-X",
    "PUT",
    `repos/${slug}/actions/permissions/workflow`,
    "-f",
    "default_workflow_permissions=write",
    "-F",
    "can_approve_pull_request_reviews=true",
  ], { cwd: folder, timeout: RUN.timeout });
  if (!permissions || permissions.status !== 0) return stopped(folder, "permissions", permissions);

  for (const item of items) {
    if (item.kind !== "variable") continue;
    for (const name of item.names) {
      const set = run("gh", ["variable", "set", name, "--body", String(item.value), "--repo", slug], {
        cwd: folder,
        timeout: RUN.timeout,
      });
      if (!set || set.status !== 0) return stopped(folder, "variables", set);
    }
  }

  const cycleSecrets = items.filter((item) => item.kind === "secret" && item.blocks === "cycle");
  if (process.stdin.isTTY) {
    for (const item of cycleSecrets) {
      console.log(item.title);
      for (const step of item.steps) console.log(step);
      const first = item.names[0];
      process.stdout.write(`Set ${first} now? (yes/no) [yes]: `);
      const line = await read();
      if (line === null) return stopped(folder, "secrets", null);
      const choice = line.trim().toLowerCase();
      if (choice !== "" && choice !== "yes") continue;
      if (typeof read.pause === "function") read.pause();
      const set = run("gh", ["secret", "set", first, "--repo", slug], {
        cwd: folder,
        stdio: "inherit",
        timeout: 600000,
      });
      if (typeof read.resume === "function") read.resume();
      if (!set || set.status !== 0) return stopped(folder, "secrets", set);
    }
  } else {
    console.log("devos: set these yourself (gh asks for each value):");
    for (const item of cycleSecrets) console.log(`gh secret set ${item.names[0]} --repo ${slug}`);
  }

  const secretList = run("gh", ["secret", "list", "--repo", slug, "--json", "name"], { cwd: folder, timeout: RUN.timeout });
  if (!secretList || secretList.status !== 0) return stopped(folder, "check", secretList);
  const variableList = run("gh", ["variable", "list", "--repo", slug, "--json", "name,value"], {
    cwd: folder,
    timeout: RUN.timeout,
  });
  if (!variableList || variableList.status !== 0) return stopped(folder, "check", variableList);
  let listed;
  let variables;
  try {
    listed = new Set(JSON.parse(secretList.stdout).map((row) => row.name));
    variables = {};
    for (const row of JSON.parse(variableList.stdout)) variables[row.name] = row.value;
  } catch {
    return stopped(folder, "check", secretList);
  }
  const secretsJson = {};
  for (const name of secretNames(setup)) secretsJson[name] = listed.has(name) ? "1" : "";
  const env = {
    ...process.env,
    SECRETS_JSON: JSON.stringify(secretsJson),
    VARS_JSON: JSON.stringify(variables),
  };
  delete env.VERCEL_TOKEN;
  delete env.VERCEL_ORG_ID;
  delete env.VERCEL_PROJECT_ID;
  const check = spawnSync(process.execPath, ["scripts/devos/setup-check.mjs", "--for", "cycle"], {
    cwd: folder,
    encoding: "utf8",
    windowsHide: true,
    env,
  });
  if (check.stdout) process.stdout.write(check.stdout);
  if (check.status !== 0) {
    console.log(`devos: the cycle still needs settings (see SETUP.md); add them, then run: devos init --continue ${folder}`);
    return 1;
  }

  const wait = Number(process.env.DEVOS_RETRY_MS ?? 10000);
  let dispatched = null;
  for (let attempt = 0; attempt < 3; attempt += 1) {
    if (attempt > 0) await delay(wait);
    dispatched = run("gh", ["workflow", "run", "devos-cycle.yml", "--repo", slug], { cwd: folder, timeout: RUN.timeout });
    if (dispatched && dispatched.status === 0) break;
  }
  if (!dispatched || dispatched.status !== 0) return stopped(folder, "cycle", dispatched);
  console.log(`devos init: ${slug} is set up; devos-cycle dispatched`);
  return 0;
}
