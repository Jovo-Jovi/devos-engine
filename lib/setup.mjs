const SWITCH_TOOLS = ["claude", "cursor", "codex", "gemini"];

/** Every project switch, with the value `devos init` and `devos adopt` set, in the order they are set. */
export function switchVariables(agents) {
  const roster = agents ?? {};
  const pairs = [
    ["DEVOS_PAUSED", "false"],
    ["DEVOS_SUPERVISOR", "on"],
    ["DEVOS_HEAVY", "notify"],
    ["DEVOS_ACCOUNT_SWITCH", "auto"],
  ];
  const used = new Set();
  const consider = (agent) => {
    if (agent && agent.tool) used.add(agent.tool);
  };
  consider(roster.reviewer);
  consider(roster.reviewer_light);
  for (const agent of roster.pool ?? []) consider(agent);
  for (const tool of SWITCH_TOOLS) {
    if (used.has(tool)) pairs.push([`DEVOS_${tool.toUpperCase()}_ACCOUNT`, "1"]);
  }
  const model = (agent, name) => {
    const id = agent?.model;
    if (typeof id === "string" && MODEL_ID.test(id)) pairs.push([name, id]);
  };
  model(roster.reviewer, "DEVOS_REVIEWER_MODEL");
  model(roster.reviewer_light, "DEVOS_REVIEWER_LIGHT_MODEL");
  model((roster.pool ?? []).find((item) => item && item.default === true), "DEVOS_BUILDER_MODEL");
  pairs.push(["DEVOS_SCREENS_RETENTION_DAYS", "3"]);
  return pairs;
}

export function interactive(read) {
  if (read && typeof read.interactive === "boolean") return read.interactive;
  if (read && typeof read.isTTY === "boolean") return read.isTTY;
  return Boolean(process.stdin.isTTY);
}

