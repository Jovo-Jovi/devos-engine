function profileOwner() {
  try {
    const file = path.join(devosHome(), ".devos", "profile.json");
    if (!existsSync(file)) return "";
    const data = JSON.parse(readFileSync(file, "utf8"));
    if (data && typeof data.github_owner === "string" && data.github_owner.length > 0) return data.github_owner;
  } catch {
    /* an unreadable profile falls through to gh */
  }
  return "";
}

function stopped(folder, step, result) {
  const stderr = result?.stderr ?? "";
  if (stderr) process.stderr.write(stderr.endsWith("\n") ? stderr : `${stderr}\n`);
  console.log(`devos: setup stopped at ${step}; fix it, then run: devos continue ${folder}`);
  return 1;
}

function git(folder, args) {
  return run("git", args, { cwd: folder, timeout: RUN.timeout });
}

export function secretNamesOnRepo(folder, slug) {
  const listed = run("gh", ["secret", "list", "--repo", slug, "--json", "name"], { cwd: folder, timeout: RUN.timeout });
  if (!listed || listed.status !== 0) return null;
  try {
    return new Set(JSON.parse(listed.stdout).map((row) => row.name));
  } catch {
    return null;
  }
}

function adoptEmptyRepo(folder, slug, created) {
  const viewed = run("gh", ["repo", "view", slug, "--json", "name,isEmpty,url"], { cwd: folder, timeout: RUN.timeout });
  if (!viewed || viewed.status !== 0) return stopped(folder, "repository", created);
  let info;
  try {
    info = JSON.parse(viewed.stdout);
  } catch {
    return stopped(folder, "repository", created);
  }
  if (info.isEmpty !== true) {
    console.log(`devos: ${slug} already exists and has commits; delete it or change "name" in devos/answers.json, then run devos continue ${folder}`);
    return 1;
  }
  const url = `${String(info.url ?? "").replace(/\.git$/, "")}.git`;
  const current = git(folder, ["remote", "get-url", "origin"]);
  const aimed = current && current.status === 0
    ? git(folder, ["remote", "set-url", "origin", url])
    : git(folder, ["remote", "add", "origin", url]);
  if (!aimed || aimed.status !== 0) return stopped(folder, "repository", aimed);
  console.log(`devos: adopted the existing empty repository ${slug}`);
  return true;
}

