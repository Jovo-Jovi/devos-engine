function agentTools(folder) {
  if (!folder) return null;
  try {
    const config = JSON.parse(readFileSync(path.join(folder, "devos.config.json"), "utf8"));
    const agents = config.agents ?? {};
    return new Set(
      [agents.reviewer, agents.reviewer_light, ...(agents.pool ?? [])].filter(Boolean).map((agent) => agent.tool),
    );
  } catch {
    return null;
  }
}

function holds(cond, answers, tools, item) {
  if (cond === "always") return true;
  if (cond === "method") return false;
  if (cond === "var:DEVOS_VERCEL") return answers.deploy === "vercel";
  if (cond.startsWith("module:")) {
    if (!item || item.kind !== "secret") return false;
    return methodModules(answers?.modules ?? {}).includes(cond.slice(7));
  }
  if (cond.startsWith("tool:")) return tools ? tools.has(cond.slice(5)) : true;
  // PR-81: the provider of generated media chosen at setup.
  if (cond.startsWith("media:")) return answers?.modules?.media === cond.slice(6);
  // PR-53: a module the project chose at devos init (the hosting choice gives vercel).
  if (cond.startsWith("chosen:")) {
    const name = cond.slice(7);
    return (name === "vercel" && answers.deploy === "vercel") || methodModules(answers?.modules ?? {}).includes(name);
  }
  return false;
}

export function setupItems(setup, answers, folder) {
  const tools = agentTools(folder);
  return (setup.items ?? []).filter((item) => {
    const when = item.when ?? ["always"];
    if (!when.every((cond) => holds(cond, answers, tools, item))) return false;
    if (item.id === "vercel-var" && answers.deploy !== "vercel") return false;
    return true;
  });
}

export function setupMarkdown(items, { name, slug, appKeys: appKeyNames = [], by = "devos init" }) {
  const lines = [
    `# SETUP — ${name}`,
    "",
    `Generated by ${by} from devos/setup.json. Names only: DEV_OS never reads or stores a value.`,
  ];
  items.forEach((item, index) => {
    lines.push("", `## ${index + 1}. ${item.title}`, "", `Names: ${item.names.map((entry) => `\`${entry}\``).join(", ")}`, "");
    item.steps.forEach((step, stepIndex) => {
      lines.push(`${stepIndex + 1}. ${step}`);
    });
    if (item.kind === "secret") {
      lines.push("", "```");
      for (const entry of item.names) lines.push(`gh secret set ${entry} --repo ${slug}`);
      lines.push("```");
    } else if (item.kind === "variable") {
      lines.push("", "```");
      for (const entry of item.names) lines.push(`gh variable set ${entry} --body ${item.value} --repo ${slug}`);
      lines.push("```");
    }
  });
  if (appKeyNames.length > 0) {
    lines.push("", "## Keys your app reads", "", "DEV_OS stored these as GitHub secrets. Until the deploy copies them to your host, also set them in Vercel → Settings → Environment Variables (Production).", "");
    for (const keyName of appKeyNames) lines.push(`- ${keyName} — ${keySource(keyName)}`);
  }
  return `${lines.join("\n")}\n`;
}

/** PR-53 (E22h): the README of a new project, from its answers at devos init. Written only when the project has none. */
export function projectReadme(answers, slug = "") {
  const catalogue = loadCatalogue();
  const type = catalogue.types.find((item) => item.id === answers.type)?.label ?? answers.type ?? "";
  const stack = catalogue.stacks.find((item) => item.id === answers.stack)?.label ?? answers.stack ?? "";
  const chosen = Object.entries(answers.modules ?? {})
    .filter(([, value]) => value && value !== "none")
    .map(([id, value]) => {
      const module = catalogue.modules.find((item) => item.id === id);
      const provider = module?.providers?.find((item) => item.id === value);
      return `${module?.label ?? id}: ${provider?.label ?? value}`;
    });
  const lines = [`# ${answers.name}`, ""];
  if (answers.brief) lines.push(String(answers.brief).trim(), "");
  if (answers.users) lines.push(`- **For:** ${answers.users}`);
  if (type) lines.push(`- **Type:** ${type}`);
  if (stack) lines.push(`- **Stack:** ${stack}`);
  lines.push(`- **Modules:** ${chosen.length > 0 ? chosen.join(" · ") : "none"}`);
  lines.push(`- **Deploy:** ${answers.deploy === "vercel" ? "Vercel" : "none"}`);
  if (Array.isArray(answers.languages) && answers.languages.length > 0) lines.push(`- **Languages:** ${answers.languages.join(", ")}`);
  return [...lines, ...projectReadmeHow(answers, slug)].join("\n");
}

/** PR-77: the lines setup adds once, from the blank line before `## How this project is built` through the end. */
export function projectReadmeHow(answers, slug = "") {
  const lines = ["", "## How this project is built", ""];
  if (answers.cycle === "local") {
    lines.push(
      "DEV_OS builds this project on this computer, one task at a time, with the agents and models chosen at `devos init`:",
      "",
      "- The plan is in `docs/`: the brief (`docs/PRODUCT_BRIEF.md`), the scope (`docs/SCOPE.md`) and the task ledger (`docs/PHASES.md`). Each task has a fence in `docs/fences/`.",
      "- Each task is built in your IDE from its fence, on a branch `task/Tnn`, pushed, and reviewed by the reviewer (`docs/method/DEV_OS_V2_REVIEWER.md`), who writes the next fence. You merge.",
      "- What this computer needs is in `SETUP.md`. The method is in `docs/method/`.",
      "",
    );
  } else {
    lines.push(
      "DEV_OS builds this repository on GitHub, one task at a time, with the agents and models chosen at `devos init`:",
      "",
      "- The plan is in `docs/`: the brief (`docs/PRODUCT_BRIEF.md`), the scope (`docs/SCOPE.md`) and the task ledger (`docs/PHASES.md`). Each task has a fence in `docs/fences/`.",
      "- `devos-cycle` builds the next open task on a branch `task/Tnn` with the builder agent, runs the checks, and has the reviewer agent review it. A PASS merges by itself, unless the task waits at a human gate for your merge.",
      "- A change is an issue with the \"Dev OS change request\" form: the reviewer agent plans it in an intake pull request.",
      `- The settings the workflows need are in \`SETUP.md\`${slug ? `, and the issue "Dev OS: setup needed" on ${slug} lists what is missing` : ""}. The method is in \`docs/method/\`.`,
      "",
    );
  }
  return lines;
}

/** PR-77: write the product README when none exists; otherwise add how the project is built, once. */
export function writeProjectReadme(folder, answers, slug = "") {
  const readme = path.join(folder, "README.md");
  if (!existsSync(readme)) {
    writeFileSync(readme, projectReadme(answers, slug));
    return;
  }
  const text = readFileSync(readme, "utf8");
  if (text.split(/\r?\n/).includes("## How this project is built")) return;
  writeFileSync(readme, `${text.replace(/\s*$/, "\n")}${projectReadmeHow(answers, slug).join("\n")}`);
}

