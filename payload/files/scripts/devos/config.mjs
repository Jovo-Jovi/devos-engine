import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { P, readJson } from "./lib.mjs";

export const GENERATED = "Generated by scripts/devos/config.mjs from devos/engine.defaults.json and devos/project.json. Edit devos/project.json, never this file (PR-39).";

function isPlainObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function joinPath(prefix, key) {
  return prefix ? `${prefix}.${key}` : key;
}

function mergeObjects(defaults, project, prefix) {
  const result = {};
  const projectKeys = Object.keys(project);

  for (const key of Object.keys(defaults)) {
    if (Object.hasOwn(project, key) && !key.startsWith("$")) {
      const value = project[key];
      if (value === null) continue;
      if (isPlainObject(value) && isPlainObject(defaults[key])) {
        result[key] = mergeObjects(defaults[key], value, joinPath(prefix, key));
      } else {
        result[key] = value;
      }
    } else {
      result[key] = defaults[key];
    }
  }

  for (const key of projectKeys) {
    if (!key.endsWith("_extra") || key.startsWith("$")) continue;
    const base = key.slice(0, -"_extra".length);
    const basePath = joinPath(prefix, base);
    const extraPath = joinPath(prefix, key);
    if (!Array.isArray(defaults[base]) || !Array.isArray(project[key])) {
      throw new Error(`config: ${extraPath} needs an array ${basePath}`);
    }
    const current = Array.isArray(result[base]) ? result[base] : defaults[base];
    result[base] = [...current, ...project[key]];
  }

  for (const key of projectKeys) {
    if (key.startsWith("$") || key.endsWith("_extra")) continue;
    if (Object.hasOwn(defaults, key)) continue;
    if (project[key] === null) continue;
    result[key] = project[key];
  }

  return result;
}

export function merge(defaults, project) {
  const body = mergeObjects(defaults, isPlainObject(project) ? project : {}, "");
  return { $generated: GENERATED, ...body };
}

export function firstDifference(expected, actual, prefix = "") {
  if (isPlainObject(expected) && isPlainObject(actual)) {
    const keys = [...new Set([...Object.keys(expected), ...Object.keys(actual)])];
    for (const key of keys) {
      const next = joinPath(prefix, key);
      if (!Object.hasOwn(expected, key) || !Object.hasOwn(actual, key)) return next;
      const diff = firstDifference(expected[key], actual[key], next);
      if (diff) return diff;
    }
    return null;
  }
  if (Array.isArray(expected) && Array.isArray(actual)) {
    if (expected.length !== actual.length) return prefix;
    for (let index = 0; index < expected.length; index += 1) {
      const diff = firstDifference(expected[index], actual[index], `${prefix}.${index}`);
      if (diff) return diff;
    }
    return null;
  }
  return Object.is(expected, actual) ? null : prefix;
}

export function jsonText(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

export function build() {
  if (!existsSync(P("devos/project.json"))) {
    const error = new Error("no devos/project.json: nothing to generate");
    error.exitCode = 2;
    throw error;
  }
  return merge(readJson("devos/engine.defaults.json"), readJson("devos/project.json"));
}

function isDirectRun() {
  const entry = process.argv[1];
  if (!entry) return false;
  return import.meta.url === pathToFileURL(path.resolve(entry)).href;
}

function failCheck(filePath) {
  console.log(filePath);
  process.exit(1);
}

if (isDirectRun()) {
  const write = process.argv.includes("--write");
  const print = process.argv.includes("--print");
  const check = process.argv.includes("--check");
  if (!write && !print && !check) {
    console.error("usage: node scripts/devos/config.mjs --write|--check|--print");
    process.exit(2);
  }
  let merged;
  try {
    merged = build();
  } catch (error) {
    console.error(error.message);
    process.exit(error.exitCode ?? 1);
  }
  if (check) {
    if (!existsSync(P("devos.config.json"))) failCheck("devos.config.json");
    const diff = firstDifference(merged, readJson("devos.config.json"));
    if (diff) failCheck(diff);
    console.log("devos.config.json is current");
    process.exit(0);
  }
  const text = jsonText(merged);
  if (write) {
    writeFileSync(P("devos.config.json"), text);
    console.log(`devos.config.json written (${Object.keys(merged).length} top-level keys)`);
  }
  if (print) process.stdout.write(text);
}
